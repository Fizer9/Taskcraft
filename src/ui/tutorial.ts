export function openTutorial(store: Store) {
  let page = 0;
  const { root, close } = openModal('<div class="tut"></div>', 'wide');
  const body = root.querySelector('.tut') as HTMLElement;
  const finish = () => {
    close();
    if (!store.state.tutorialDone) store.finishTutorial();
  };
  const render = () => {
    const p = PAGES[page];
    const last = page === PAGES.length - 1;
    body.innerHTML =
      `<div class="tut-head"><span class="tut-icon">${p.icon}</span><h3>${p.title}</h3></div>` +
      p.text.map((t) => `<p>${t}</p>`).join('') +
      `<div class="tut-dots">${PAGES.map((_, i) => `<span class="${i === page ? 'on' : ''}"></span>`).join('')}</div>` +
      `<div class="actions">` +
      (last ? '' : '<button class="btn" data-a="skip" style="margin-right:auto">Пропустить</button>') +
      (page ? '<button class="btn" data-a="back">Назад</button>' : '') +
      `<button class="btn" data-a="next">${last ? 'В бой!' : 'Дальше'}</button></div>`;
    // Каждая страница звучит как подсказка в WC3.
    void sounds.play('hint');
  };
  body.addEventListener('click', (e) => {
    const a = (e.target as HTMLElement).closest<HTMLElement>('[data-a]')?.dataset.a;
    if (a === 'skip') finish();
    else if (a === 'back') page = Math.max(0, page - 1);
    else if (a === 'next') {
      if (page === PAGES.length - 1) return finish();
      page++;
    }
    if (a === 'back' || a === 'next') render();
  });
  render();
}
